const key='presto-ui-language';
type Context={language:Language;setLanguage:(lang:Language)=>void;t:(text:string)=>string};
const I18n=createContext<Context|null>(null);
export function LanguageProvider({children}:{children:ReactNode}){
 const [language,setLanguage]=useState<Language>('fr');
 const [loaded,setLoaded]=useState(false);
 useEffect(()=>{try{const stored=localStorage.getItem(key);if(stored==='ar'||stored==='fr')setLanguage(stored)}catch{}setLoaded(true)},[]);
 useEffect(()=>{
  const root=document.documentElement;root.lang=language;root.dir=language==='ar'?'rtl':'ltr';
  if(loaded){try{localStorage.setItem(key,language)}catch{}}
 },[language,loaded]);
 const t=(text:string)=>language==='ar'?(ar[text]||text):text;
 return <I18n.Provider value={{language,setLanguage,t}}>{children}</I18n.Provider>;
}
export function useLanguage(){const ctx=useContext(I18n);if(!ctx)throw new Error('LanguageProvider missing');return ctx}
export function LanguageSwitcher(){
 const {language,setLanguage}=useLanguage();
 return <div className="prestoLanguagePicker" role="group" aria-label="Langue / اللغة">
  <button type="button" lang="fr" aria-pressed={language==='fr'} className={language==='fr'?'active':''} onClick={()=>setLanguage('fr')}>FR</button>
  <button type="button" lang="ar" aria-pressed={language==='ar'} className={language==='ar'?'active':''} onClick={()=>setLanguage('ar')}>عربي</button>
 </div>;
}
