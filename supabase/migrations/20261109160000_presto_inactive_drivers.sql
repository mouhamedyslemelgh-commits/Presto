create table if not exists public.presto_inactive_drivers (
 id bigint generated by default as identity primary key,
 name text not null check(length(trim(name)) between 1 and 150),
 phone text not null check(length(trim(phone)) between 1 and 150),
 app_code text not null default '', group_no integer not null default 1 check(group_no between 1 and 3),
 trained boolean not null default false, bag_date text not null default '',last_seen text not null default '',
 answered text not null default '' check(answered in ('','نعم','لا')),
 reason text not null default '' check(length(reason)<=1000),decision text not null default '',
 created_at timestamptz not null default now()
);
alter table public.presto_inactive_drivers enable row level security;
grant select on public.presto_inactive_drivers to authenticated;
grant insert,update on public.presto_inactive_drivers to authenticated;
grant usage,select on sequence public.presto_inactive_drivers_id_seq to authenticated;
create policy inactive_read on public.presto_inactive_drivers for select to authenticated using(exists(select 1 from public.presto_admins where user_id=(select auth.uid())));
create policy inactive_insert on public.presto_inactive_drivers for insert to authenticated with check(exists(select 1 from public.presto_admins where user_id=(select auth.uid())));
create policy inactive_update on public.presto_inactive_drivers for update to authenticated using(exists(select 1 from public.presto_admins where user_id=(select auth.uid()))) with check(exists(select 1 from public.presto_admins where user_id=(select auth.uid())));
